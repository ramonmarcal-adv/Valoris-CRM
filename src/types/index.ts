export interface Message {
  id: string;
  conversation_id: string;
  sender_type: SenderType;
  /** Only meaningful when the parent conversation is_group=true: the
   *  contacts.id of the individual participant who sent this message
   *  inside the group (migration 049). NULL for 1:1 conversations and
   *  NULL when an inbound participant JID couldn't be resolved to a
   *  contact (e.g. a Baileys @lid identity). */
  sender_id?: string;
  /** Embedded contacts row for `sender_id`, when the fetch query joins
   *  it (message-thread.tsx does) — the group participant who sent
   *  this message. Undefined when the query didn't embed it; null when
   *  `sender_id` itself is null. */
  sender?: { id: string; name?: string; avatar_url?: string; phone: string } | null;
  /** Resolved @mentions for a group text message (migration 051) —
   *  `jid` is the raw Baileys JID/lid that was mentioned; `phone`/`name`
   *  are best-effort resolutions against the group's participant list
   *  (either can be null if the participant couldn't be resolved).
   *  Used to replace the raw `@<digits>` placeholder in `content_text`
   *  with a real name. Absent/null on every 1:1 message and on group
   *  messages that don't mention anyone. */
  mentions?: { jid: string; phone: string | null; name: string | null }[] | null;
  content_type: ContentType;
  content_text?: string;
  media_url?: string;
  template_name?: string;
  message_id?: string;
  status: MessageStatus;
  created_at: string;
  reply_to_message_id?: string;
  /**
   * Only set when `content_type === 'interactive'` — the stable id of
   * the button or list row the customer tapped. The Flows engine uses
   * this to route the next node; the inbox bubble uses it as a styling
   * cue (renders with a "↩ button reply" affordance).
   */
  interactive_reply_id?: string;
  /**
   * Structured payload of an OUTBOUND interactive message (reply
   * buttons or list) we sent. Lets the thread re-render the buttons /
   * rows, not just the body text. Only set when `content_type ===
   * 'interactive'` and `sender_type` is agent/bot. Migration 035.
   */
  interactive_payload?: InteractiveMessagePayload;
  /**
   * True when the AI auto-reply bot generated + sent this message (as
   * opposed to a human agent or a deterministic Flow/automation send,
   * which all share `sender_type='bot'`/`'agent'`). Drives the "AI"
   * badge in the inbox. Migration 033.
   */
  ai_generated?: boolean;
}

